export function detectLanguage() {
  let stored = null;
  try { stored = window.localStorage.getItem(STORAGE_KEY); } catch { /* storage may be disabled */ }
  if (LANGS.includes(stored)) return stored;
  const browser = String(navigator.language || 'en').toLowerCase();
  return browser.startsWith('fr') ? 'fr' : 'en';
}

export let currentLanguage = detectLanguage();

export function setLanguage(next) {
  currentLanguage = LANGS.includes(next) ? next : 'en';
}

export function t(key, vars = {}) {
  const table = MESSAGES[currentLanguage] || MESSAGES.en;
  let text = table[key];
  if (text == null) text = MESSAGES.en[key];
  if (text == null) return key;
  return text.replace(/\{(\w+)\}/g, (_, name) => (vars[name] == null ? '' : String(vars[name])));
}

export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  root.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel));
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
}

export function otherLanguage() {
  return currentLanguage === 'fr' ? 'en' : 'fr';
}
